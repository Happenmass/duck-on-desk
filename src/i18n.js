function createTranslator(getLang) {
  if (typeof getLang !== "function") {
    throw new TypeError("createTranslator(getLang): getLang must be a function");
  }
  return function t(key) {
    const lang = getLang();
    const dict = i18n[lang] || i18n.en;
    return dict[key] || key;
  };
}

module.exports = {
  i18n,
  SUPPORTED_LANGS,
  createTranslator,
};
